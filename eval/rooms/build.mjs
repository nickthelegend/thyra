// Builds Thyra's emulator rooms (GLTS) for IWER's Synthetic Environment Module.
// Each room = IWER SEM's room kit (MIT, extracted from the installed
// @iwsdk/vite-plugin-dev bundle, not copied into this repo) + one of our room
// scripts in ./src. Output: packages/xr/public/rooms/<name>.glts (gitignored).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const chunks = `${here}../../packages/xr/node_modules/@iwsdk/vite-plugin-dev/dist/injection/chunks/`;
const host = readdirSync(chunks).find((f) => f.startsWith('home_office-'));
if (!host) throw new Error(`IWER room kit not found in ${chunks}; run npm install in packages/xr first.`);
const bundle = readFileSync(chunks + host, 'utf8');
const m = bundle.match(/var n=("(?:[^"\\]|\\.)*")/);
if (!m) throw new Error('Unexpected IWER room bundle format');
const lines = JSON.parse(m[1]).split('\n');
const roomStart = lines.findIndex((l) => /^const room = createRoom/.test(l));
if (roomStart < 0) throw new Error('Room kit boundary not found');
const kit = lines.slice(1, roomStart).join('\n'); // drop the "Generated by" line
const out = `${here}../../packages/xr/public/rooms/`;
mkdirSync(out, { recursive: true });
for (const f of readdirSync(`${here}src`).filter((x) => x.endsWith('.ts'))) {
  const name = f.replace(/\.ts$/, '');
  const script = readFileSync(`${here}src/${f}`, 'utf8');
  writeFileSync(`${out}${name}.glts`, `// Built by eval/rooms/build.mjs: IWER SEM room kit (MIT) + eval/rooms/src/${f}\n${kit}\n${script}\n`);
  console.log(`rooms: ${name}.glts`);
}
